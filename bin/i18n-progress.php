<?php
/**
 * Indicador de progresso de tradução (Story 1.21 AC 4, 7, 8 — FR-30).
 *
 * Calcula a porcentagem a partir dos `.po` REAIS e escreve uma tabela Markdown com barra
 * Unicode entre os marcadores `<!-- i18n-progress:start -->` e `<!-- i18n-progress:end -->`
 * dos READMEs.
 *
 * Sem shields.io, sem badge externo, sem serviço de terceiro — de propósito. Um indicador
 * que depende de um serviço externo é um indicador que um dia mostra "unknown" num README
 * que ninguém está olhando, e é também um pixel de rastreamento embutido na página do
 * projeto. A barra é texto.
 *
 * Uso:
 *   php bin/i18n-progress.php              # recalcula e escreve nos READMEs
 *   php bin/i18n-progress.php --check      # falha se a tabela estiver desatualizada
 *   php bin/i18n-progress.php --check --require-complete=pt_BR,en_US,es_ES
 *
 * @package WpRecaptchaForms
 */

declare( strict_types = 1 );

require_once __DIR__ . '/i18n-po.php';

/**
 * Idioma-fonte: o catálogo identidade, 100% por definição (AC 4).
 *
 * **Desvio deliberado do enunciado do AC 4, registrado na story.** O AC diz `en_US`, mas
 * os `msgid` do código estão em português — foi assim que o plugin foi escrito. O idioma
 * identidade é, portanto, `pt_BR`. Declarar `en_US` como identidade produziria um README
 * afirmando 100% de cobertura em inglês sobre um catálogo vazio, que é exatamente o tipo
 * de indicador falso que o FR-30 existe para não ter.
 */
const WRF_SOURCE_LOCALE = 'pt_BR';

/** Idiomas mantidos pelo projeto (entram com `.po` e `.mo`; AC 9). */
const WRF_MAINTAINED = array( 'pt_BR', 'en_US', 'es_ES' );

/** Nomes exibidos. */
const WRF_LOCALE_NAMES = array(
	'pt_BR' => 'Português (Brasil)',
	'en_US' => 'English (US)',
	'es_ES' => 'Español',
);

const WRF_MARK_START = '<!-- i18n-progress:start -->';
const WRF_MARK_END   = '<!-- i18n-progress:end -->';

/**
 * Total de strings traduzíveis no `.pot`.
 *
 * Cabeçalho (msgid vazio) e entradas obsoletas ficam de fora — o parser já descarta as
 * obsoletas.
 *
 * @param string $pot Caminho do `.pot`.
 * @return int
 */
function wrf_progress_total( string $pot ): int {
	$total = 0;

	foreach ( wrf_po_parse( $pot ) as $entry ) {
		if ( '' !== $entry['msgid'] ) {
			++$total;
		}
	}

	return $total;
}

/**
 * Quantas strings estão traduzidas num catálogo.
 *
 * @param string $po    Caminho do `.po`.
 * @param int    $total Total do `.pot`.
 * @return int
 */
function wrf_progress_done( string $po, int $total ): int {
	if ( ! is_readable( $po ) ) {
		return 0;
	}

	$done = 0;

	foreach ( wrf_po_parse( $po ) as $entry ) {
		if ( '' === $entry['msgid'] ) {
			continue;
		}

		if ( wrf_po_is_translated( $entry ) ) {
			++$done;
		}
	}

	return min( $done, $total );
}

/**
 * Barra Unicode de 20 células.
 *
 * @param int $percent Percentual.
 * @return string
 */
function wrf_progress_bar( int $percent ): string {
	$filled = (int) round( $percent / 5 );

	return str_repeat( '█', $filled ) . str_repeat( '░', 20 - $filled );
}

/**
 * Monta a tabela Markdown.
 *
 * @param array<string, array{done:int,total:int,percent:int}> $stats Estatísticas.
 * @param bool                                                 $ptbr  Se os rótulos saem em pt-BR.
 * @return string
 */
function wrf_progress_table( array $stats, bool $ptbr ): string {
	$head = $ptbr
		? "| Idioma | Progresso | Strings |\n|---|---|---|"
		: "| Language | Progress | Strings |\n|---|---|---|";

	$rows = array( $head );

	foreach ( $stats as $locale => $stat ) {
		$name = WRF_LOCALE_NAMES[ $locale ] ?? $locale;

		if ( WRF_SOURCE_LOCALE === $locale ) {
			$name .= $ptbr ? ' — idioma-fonte' : ' — source language';
		}

		$rows[] = sprintf(
			'| %s (`%s`) | `%s` %d%% | %d/%d |',
			$name,
			$locale,
			wrf_progress_bar( $stat['percent'] ),
			$stat['percent'],
			$stat['done'],
			$stat['total']
		);
	}

	$note = $ptbr
		? "\nGerado por `composer i18n:progress` a partir dos `.po` do diretório `languages/`. Não editar à mão."
		: "\nGenerated by `composer i18n:progress` from the actual `.po` files in `languages/`. Do not edit by hand.";

	return implode( "\n", $rows ) . "\n" . $note . "\n";
}

/**
 * Substitui o bloco entre os marcadores.
 *
 * @param string $path  Caminho do README.
 * @param string $table Tabela.
 * @return array{0:bool, 1:string} Mudou? e conteúdo final.
 */
function wrf_progress_apply( string $path, string $table ) {
	$content = (string) file_get_contents( $path );
	$start   = strpos( $content, WRF_MARK_START );
	$end     = strpos( $content, WRF_MARK_END );

	if ( false === $start || false === $end || $end < $start ) {
		fwrite( STDERR, sprintf( "FALHOU: marcadores i18n-progress ausentes em %s\n", basename( $path ) ) );
		exit( 1 );
	}

	$updated = substr( $content, 0, $start )
		. WRF_MARK_START . "\n\n" . $table . "\n" . WRF_MARK_END
		. substr( $content, $end + strlen( WRF_MARK_END ) );

	return array( $updated !== $content, $updated );
}

// ---------------------------------------------------------------------------
// Execução.
// ---------------------------------------------------------------------------

$wrf_root  = dirname( __DIR__ );
$wrf_args  = array_slice( $argv, 1 );
$wrf_check = in_array( '--check', $wrf_args, true );
$wrf_need  = array();

foreach ( $wrf_args as $wrf_arg ) {
	if ( 0 === strpos( $wrf_arg, '--require-complete=' ) ) {
		$wrf_need = array_filter( explode( ',', substr( $wrf_arg, 19 ) ) );
	}
}

$wrf_total = wrf_progress_total( $wrf_root . '/languages/wp-recaptcha-forms.pot' );

if ( 0 === $wrf_total ) {
	fwrite( STDERR, "FALHOU: .pot vazio. Rode `composer i18n:pot`.\n" );
	exit( 1 );
}

$wrf_stats = array();

foreach ( WRF_MAINTAINED as $wrf_locale ) {
	$wrf_done = WRF_SOURCE_LOCALE === $wrf_locale
		? $wrf_total
		: wrf_progress_done( $wrf_root . '/languages/wp-recaptcha-forms-' . $wrf_locale . '.po', $wrf_total );

	$wrf_stats[ $wrf_locale ] = array(
		'done'    => $wrf_done,
		'total'   => $wrf_total,
		'percent' => (int) round( $wrf_done / $wrf_total * 100 ),
	);
}

$wrf_targets = array(
	$wrf_root . '/README.md'    => true,
	$wrf_root . '/README-EN.md' => false,
);

$wrf_stale = array();

foreach ( $wrf_targets as $wrf_path => $wrf_ptbr ) {
	if ( ! is_file( $wrf_path ) ) {
		continue;
	}

	list( $wrf_changed, $wrf_content ) = wrf_progress_apply( $wrf_path, wrf_progress_table( $wrf_stats, $wrf_ptbr ) );

	if ( ! $wrf_changed ) {
		continue;
	}

	if ( $wrf_check ) {
		$wrf_stale[] = basename( $wrf_path );
		continue;
	}

	file_put_contents( $wrf_path, $wrf_content );

	printf( "atualizado: %s\n", basename( $wrf_path ) );
}

foreach ( $wrf_stats as $wrf_locale => $wrf_stat ) {
	printf( "%-6s %3d%%  %d/%d\n", $wrf_locale, $wrf_stat['percent'], $wrf_stat['done'], $wrf_stat['total'] );
}

$wrf_failed = false;

if ( array() !== $wrf_stale ) {
	fwrite( STDERR, sprintf( "\nFALHOU: tabela de progresso desatualizada em: %s\nRode `composer i18n:progress`.\n", implode( ', ', $wrf_stale ) ) );
	$wrf_failed = true;
}

foreach ( $wrf_need as $wrf_locale ) {
	$wrf_locale = trim( $wrf_locale );

	if ( 100 !== ( $wrf_stats[ $wrf_locale ]['percent'] ?? -1 ) ) {
		fwrite( STDERR, sprintf( "FALHOU: %s não está em 100%% e é idioma mantido.\n", $wrf_locale ) );
		$wrf_failed = true;
	}
}

exit( $wrf_failed ? 1 : 0 );
